import logging
import os
import re
import subprocess
import sys
from typing import List, Tuple

try:
    import polib
except ImportError:
    polib = None
from rich.console import Console
from tqdm import tqdm

from .translator import Translator

logger = logging.getLogger(__name__)
console = Console()


class SphinxHandler:
    """Handles Sphinx documentation translation using gettext and PO files."""

    def __init__(self, translator: Translator) -> None:
        """
        Initialize the SphinxHandler.

        :param translator: The Translator instance to use.
        """
        self.translator = translator

    def protect_rst(self, text: str) -> Tuple[str, List[str]]:
        """
        Replaces rST-specific syntax with placeholders to prevent translation.

        :param text: The rST text.
        :return: A tuple containing the protected text and original constructs.
        """
        placeholders = []

        def replace(match):
            placeholder = f"ROSETTA_RST_{len(placeholders)}"
            placeholders.append(match.group(0))
            return placeholder

        # Protect :role:`text`
        protected_text = re.sub(r":\w+:`[^`]+`|:\w+:\".*?\"|:\w+:'.*?'", replace, text)
        # Protect ``inline literal``
        protected_text = re.sub(r"``[^`]+``", replace, protected_text)
        # Protect `interpreted text` (single backticks)
        protected_text = re.sub(r"(?<!`)(`[^`]+`)(?!`)", replace, protected_text)
        # Protect `link <url>`_
        protected_text = re.sub(r"`[^`]+ <[^>]+>`_+", replace, protected_text)
        # Protect `target`_
        protected_text = re.sub(r"`[^`]+`_+", replace, protected_text)
        # Protect |substitution|
        protected_text = re.sub(r"\|\w+\|", replace, protected_text)
        # Protect directive-like things at the start of lines
        protected_text = re.sub(
            r"^\.\. \w+::", replace, protected_text, flags=re.MULTILINE
        )

        return protected_text, placeholders

    def restore_rst(self, text: str, placeholders: List[str]) -> str:
        """
        Restores rST-specific syntax from placeholders after translation.

        :param text: The translated text with placeholders.
        :param placeholders: The list of original rST constructs.
        :return: The restored rST text.
        """

        def replace_match(match):
            try:
                index = int(match.group(1))
                if index < len(placeholders):
                    return placeholders[index]
            except Exception:
                pass
            return match.group(0)

        pattern = re.compile(r"ROSETTA[_\s-]*RST[_\s-]*(\d+)", re.IGNORECASE)
        restored = pattern.sub(replace_match, text)
        return self.fix_rst_underlines(restored)

    def fix_rst_underlines(self, text: str) -> str:
        """
        Ensures rST underlines (===, ---, etc.) are at least as long as the preceding text.

        :param text: The rST text.
        :return: The rST text with fixed underlines.
        """
        lines = text.splitlines()
        fixed_lines = []
        for i in range(len(lines)):
            line = lines[i]
            if i > 0 and re.match(r"^([=~`'\-\^\"*+#])\1+$", line):
                prev_line = lines[i - 1].strip()
                if prev_line:
                    char = line[0]
                    if len(line) < len(prev_line):
                        line = char * len(prev_line)
            fixed_lines.append(line)
        return "\n".join(fixed_lines)

    def discover_translations(self) -> List[str]:
        """
        Scans for existing Sphinx translations in docs/source/locale.

        :return: List of language codes found.
        """
        locale_dir = os.path.join(os.getcwd(), "docs", "source", "locale")
        if not os.path.exists(locale_dir):
            return []

        langs = []
        for d in os.listdir(locale_dir):
            if os.path.isdir(os.path.join(locale_dir, d)):
                if os.path.exists(os.path.join(locale_dir, d, "LC_MESSAGES")):
                    langs.append(d)
        return sorted(langs)

    def translate_po_file(self, po_path: str, from_code: str, to_code: str) -> bool:
        """
        Translates a Sphinx PO file.

        :param po_path: The path to the .po file.
        :param from_code: The source language code.
        :param to_code: The target language code.
        :return: True if any translations were made, False otherwise.
        """
        if not polib:
            logger.warning("polib not installed, skipping PO translation")
            return False

        po = polib.pofile(po_path)
        entries_to_translate = [
            e for e in po if e.msgid and (not e.msgstr or "fuzzy" in e.flags)
        ]

        if entries_to_translate:
            console.print(
                f"Translating {len(entries_to_translate)} entries in "
                f"{os.path.basename(po_path)} to {to_code}..."
            )

            # Use batch translation for PO files
            batch_size = 32
            msgids = [e.msgid for e in entries_to_translate]
            protected_msgids = []
            all_placeholders = []

            for msgid in msgids:
                protected, placeholders = self.protect_rst(msgid)
                protected_msgids.append(protected)
                all_placeholders.append(placeholders)

            translated_msgs = []
            for i in tqdm(
                range(0, len(protected_msgids), batch_size),
                desc="Translating chunks",
                leave=False,
            ):
                batch = protected_msgids[i : i + batch_size]
                translated_msgs.extend(
                    self.translator.translate_batch(batch, from_code, to_code)
                )

            for entry, trans, placeholders in zip(
                entries_to_translate, translated_msgs, all_placeholders
            ):
                final_trans = self.restore_rst(trans, placeholders)
                entry.msgstr = final_trans
                if "fuzzy" in entry.flags:
                    entry.flags.remove("fuzzy")

            po.save()
            return True
        return False

    def setup_sphinx(
        self, project_path: str, langs: List[str], start_code: str = "en"
    ) -> None:
        """
        Sets up Sphinx documentation, generates API docs, and translates them.

        :param project_path: The path to the project source code.
        :param langs: A list of target language codes.
        :param start_code: The source language code.
        """
        docs_dir = os.path.join(os.getcwd(), "docs")
        source_dir = os.path.join(docs_dir, "source")

        python_exe = sys.executable
        env = os.environ.copy()
        env["PYTHONPATH"] = os.path.abspath(os.path.join(os.getcwd(), "src"))

        if os.path.exists(docs_dir):
            logging.info(f"Sphinx documentation directory detected: {docs_dir}")
        else:
            os.makedirs(docs_dir)
            subprocess.run(
                [
                    python_exe,
                    "-m",
                    "sphinx.cmd.quickstart",
                    "-q",
                    "--sep",
                    "-p",
                    "Project",
                    "-a",
                    "Author",
                    "-v",
                    "0.1.0",
                    docs_dir,
                ],
                env=env,
            )

        # Ensure conf.py has i18n settings and sys.path for autodoc
        conf_path = os.path.join(source_dir, "conf.py")
        if os.path.exists(conf_path):
            logging.info(f"Sphinx configuration detected: {conf_path}")
            with open(conf_path, "r", encoding="utf-8") as f:
                conf_content = f.read()

            updates = []
            if 'sys.path.insert(0, os.path.abspath("../../src"))' not in conf_content:
                updates.append(
                    'import sys, os\nsys.path.insert(0, os.path.abspath("../../src"))'
                )
            if 'locale_dirs = ["locale/"]' not in conf_content:
                updates.append('locale_dirs = ["locale/"]')
            if "gettext_compact = False" not in conf_content:
                updates.append("gettext_compact = False")

            if updates:
                with open(conf_path, "a", encoding="utf-8") as f:
                    f.write("\n" + "\n".join(updates) + "\n")

        # Run apidoc
        subprocess.run(
            [
                python_exe,
                "-m",
                "sphinx.ext.apidoc",
                "-o",
                source_dir,
                project_path,
                "-f",
            ],
            env=env,
        )

        # Generate gettext
        subprocess.run(
            [
                python_exe,
                "-m",
                "sphinx.cmd.build",
                "-M",
                "gettext",
                source_dir,
                os.path.join(docs_dir, "build"),
            ],
            env=env,
        )

        # Update and translate PO files
        for lang in tqdm(langs, desc="Sphinx Languages", position=0):
            if lang == ".":
                continue

            # Check if we can skip updating if it's already done
            locale_dir = os.path.join(source_dir, "locale", lang, "LC_MESSAGES")
            html_output = os.path.join(docs_dir, "build", "html", lang)

            console.print(f"Updating catalogs for {lang}...")
            subprocess.run(
                [
                    python_exe,
                    "-m",
                    "sphinx_intl",
                    "update",
                    "-p",
                    os.path.join(docs_dir, "build", "gettext"),
                    "-l",
                    lang,
                ],
                cwd=docs_dir,
                env=env,
                capture_output=True,
            )

            any_translated = False
            if os.path.exists(locale_dir):
                po_files = [f for f in os.listdir(locale_dir) if f.endswith(".po")]
                for f in tqdm(po_files, desc=f"PO files ({lang})", leave=False):
                    if self.translate_po_file(
                        os.path.join(locale_dir, f), start_code, lang
                    ):
                        any_translated = True

            # Build HTML for this language if needed
            if not any_translated and os.path.exists(html_output):
                console.print(
                    f"[blue]Sphinx translation for {lang} is up to date. Skipping build.[/blue]"
                )
                continue

            console.print(f"Building HTML for {lang}...")
            subprocess.run(
                [
                    python_exe,
                    "-m",
                    "sphinx.cmd.build",
                    "-b",
                    "html",
                    "-D",
                    f"language={lang}",
                    source_dir,
                    os.path.join(docs_dir, "build", "html", lang),
                ],
                env=env,
            )

        console.print("[green]Sphinx setup and translation complete.[/green]")
